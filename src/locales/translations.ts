export type TranslationDictionary = typeof translations.EN;

/**
 * Universal lookup helper supporting dot notation e.g. `getTranslation('CEB', 'nav.dashboard')`
 */
export function getTranslation(
  lang: Language | string,
  keyPath: string,
  fallback?: string
): string {
  const normalizedLang: 'EN' | 'CEB' =
    lang === 'CEB' || lang === 'Cebuano' ? 'CEB' : 'EN';
  const dict = translations[normalizedLang] || translations.EN;

  const parts = keyPath.split('.');
  let current: any = dict;

  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      // Fallback to EN if missing in CEB
      let fallbackCurrent: any = translations.EN;
      for (const fPart of parts) {
        if (fallbackCurrent && typeof fallbackCurrent === 'object' && fPart in fallbackCurrent) {
          fallbackCurrent = fallbackCurrent[fPart];
        } else {
          fallbackCurrent = null;
          break;
        }
      }
      if (typeof fallbackCurrent === 'string') {
        return fallbackCurrent;
      }
      return fallback !== undefined ? fallback : keyPath;
    }
  }

  return typeof current === 'string' ? current : (fallback !== undefined ? fallback : keyPath);
}
